// Generates tools/levels.js from hand-picked seed words using the SCOWL word lists.
// Grid words are chosen from common words (SCOWL <=35) plus up to 2 "less common" (SCOWL 40/50).
const fs = require("fs"), path = require("path");
const WL = "/workspace/wl";
const read = l => fs.readFileSync(`${WL}/lvl${l}.txt`, "utf8").split("\n").filter(Boolean);
const rank = {}; [10, 20, 35, 40, 50].forEach(l => read(l).forEach(w => { if (!(w in rank)) rank[w] = l; }));
const { BLOCK } = require("./blocklist");
const { layout } = require("./layout");
const SEEDS = require("./seeds");
const EXCLUDE = new Set(require("./exclude"));
function counts(s) { const m = {}; for (const c of s) m[c] = (m[c] || 0) + 1; return m; }
function spellable(w, L) { const a = counts(L), b = counts(w); return Object.keys(b).every(k => (a[k] || 0) >= b[k]); }
function rng(seed) { let s = seed >>> 0 || 1; return () => { s ^= s << 13; s >>>= 0; s ^= s >> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; }; }
const out = [];
SEEDS.forEach((seed, i) => {
  seed = seed.toLowerCase();
  const n = seed.length;
  const target = n === 6 ? 7 : n === 7 ? 8 : (i >= 28 ? 10 : 9);
  const cand = Object.keys(rank).filter(w => w !== seed && w.length >= 3 && w.length <= n && spellable(w, seed) && !BLOCK.has(w) && !EXCLUDE.has(w) && !(w.endsWith('s') && (w.slice(0,-1) in rank)));
  const common = cand.filter(w => rank[w] <= 35), rare = cand.filter(w => rank[w] > 35 && rank[w] <= 50 && w.length >= 5);
  const rand = rng(77 + i * 13);
  let best = null;
  for (let t = 0; t < 60 && !best; t++) {
    const pick = [seed];
    const sc = w => w.length * 3 + (rank[w] <= 20 ? 1 : 0) + rand() * 4;
    const longC = common.filter(w => w.length >= 4).sort((a, b) => sc(b) - sc(a));
    const r2 = rare.slice().sort(() => rand() - 0.5).slice(0, n >= 7 ? 2 : 1);
    pick.push(...r2);
    for (const w of longC) { if (pick.length >= target - 1) break; pick.push(w); }
    const threes = common.filter(w => w.length === 3).sort(() => rand() - 0.5);
    for (const w of threes) { if (pick.length >= target) break; pick.push(w); }
    const words = pick.map(w => w.toUpperCase());
    const L = layout(words, 500 + i * 11 + t);
    if (L && L.rows <= 11 && L.cols <= 10) best = words;
  }
  if (!best) throw new Error("no layout for " + seed);
  // letters: scramble seed deterministically so the seed isn't spelled in order
  let letters = seed.toUpperCase().split("");
  do { letters.sort(() => rand() - 0.5); } while (letters.join("") === seed.toUpperCase());
  out.push({ letters: letters.join(""), words: best });
  console.log(`L${i + 1} ${seed} -> ${best.join(" ")}  ${best.filter(w => rank[w.toLowerCase()] > 35).map(w => "[" + w + "]").join("")}`);
});
fs.writeFileSync(path.join(__dirname, "levels.js"), "// GENERATED by genlevels.js from seeds.js (review output before publishing).\nmodule.exports = " + JSON.stringify(out, null, 1) + ";\n");
